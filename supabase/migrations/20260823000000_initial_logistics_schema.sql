create function public.aplicar_movimiento_en_inventario()
returns trigger
language plpgsql
as $$
declare
    movimiento_tipo public.tipo_movimiento;
    movimiento_estado public.estado_movimiento;
    stock_actual numeric(14,3);
begin
    select tipo, estado
      into movimiento_tipo, movimiento_estado
      from public.movimientos
     where id_movimiento = new.id_movimiento
       for update;

    if not found then
        raise exception 'El movimiento % no existe', new.id_movimiento;
    end if;
    if movimiento_estado <> 'VIGENTE' then
        raise exception 'No se pueden agregar detalles a un movimiento anulado';
    end if;

    select stock
      into stock_actual
      from public.inventario
     where id_producto = new.id_producto
       for update;

    if not found then
        raise exception 'No existe inventario para el producto %', new.id_producto;
    end if;
    if movimiento_tipo = 'SALIDA' and stock_actual < new.cantidad then
        raise exception 'Stock insuficiente para el producto %', new.id_producto;
    end if;

    update public.inventario
       set stock = stock + case when movimiento_tipo = 'ENTRADA' then new.cantidad else -new.cantidad end
     where id_producto = new.id_producto;
    return new;
end;
$$;

create function public.revertir_movimiento_anulado()
returns trigger
language plpgsql
as $$
declare
    detalle record;
begin
    if old.estado = 'ANULADO' and new.estado <> 'ANULADO' then
        raise exception 'Un movimiento anulado no puede volver a estar vigente';
    end if;
    if old.estado = 'VIGENTE' and new.estado = 'ANULADO' then
        for detalle in
            select md.id_producto, md.cantidad, i.stock
              from public.movimiento_detalle md
              join public.inventario i on i.id_producto = md.id_producto
             where md.id_movimiento = old.id_movimiento
             order by md.id_producto
               for update of i
        loop
            if old.tipo = 'ENTRADA' and detalle.stock < detalle.cantidad then
                raise exception 'No se puede anular: el stock del producto % quedaría negativo', detalle.id_producto;
            end if;
            update public.inventario
               set stock = stock + case when old.tipo = 'ENTRADA' then -detalle.cantidad else detalle.cantidad end
             where id_producto = detalle.id_producto;
        end loop;
    end if;
    return new;
end;
$$;

create function public.registrar_auditoria()
returns trigger
language plpgsql
as $$
declare
    registro bigint;
begin
    if tg_op = 'DELETE' then
        registro := old.id_movimiento;
        insert into public.auditoria (tabla, id_registro, accion, datos_anteriores)
        values (tg_table_name, registro, tg_op, to_jsonb(old));
        return old;
    end if;

    registro := new.id_movimiento;
    insert into public.auditoria (tabla, id_registro, accion, datos_anteriores, datos_nuevos)
    values (tg_table_name, registro, tg_op,
            case when tg_op = 'UPDATE' then to_jsonb(old) else null end, to_jsonb(new));
    return new;
end;
$$;

